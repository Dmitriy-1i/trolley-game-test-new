function buildDeck() {
    const deck = [];
    let n = 0;
    INNOCENTS.forEach(([emoji, title, text]) => deck.push({ id: `c${n++}`, type: 'innocent', emoji, title, text }));
    VILLAINS.forEach(([emoji, title, text]) => deck.push({ id: `c${n++}`, type: 'villain', emoji, title, text }));
    ACTIONS.forEach(([action, emoji, title, text, copies]) => {
        for (let i = 0; i < copies; i++) deck.push({ id: `c${n++}`, type: 'action', action, emoji, title, text });
    });
    return deck;
}

function shuffle(arr) {
    for (let i = arr.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [arr[i], arr[j]] = [arr[j], arr[i]];
    }
    return arr;
}

